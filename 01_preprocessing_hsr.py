"""
01_preprocessing_hsr.py
=======================
Preprocessing pipeline: starrailstation-backup_*.dat -> data_clean_hsr.csv

Converts the StarRailStation backup (Honkai: Star Rail warp history) into one
tidy table (one row = one warp), with the same column layout as the Genshin
data_clean.csv so the dashboard can reuse the same logic.

Input:
    data/starrailstation-backup_YYYY-MM-DD.dat  -> raw backup (latest one is picked automatically)
    data/hsr_char_full.json                     -> id -> {name, rarity} for characters
    data/hsr_lc_full.json                       -> id -> {name, rarity} for light cones
    (both lookup files are generated by 00_fetch_hsr_lookup.py)

Output:
    data/data_clean_hsr.csv            -> default, all profiles combined
    data/data_clean_hsr_<profile>.csv  -> when run with --profile <name or key>

Backup file notes:
    * The .dat file is "srs" + an LZString(UTF-16) compressed JSON. It is
      decoded below, no extra pip package needed.
    * Every backup is a FULL snapshot (it contains the whole history), so each
      run simply rebuilds the CSV from the newest backup. No merging needed.
    * The backup has no game UID. Accounts are the StarRailStation profiles.

Usage:
    python3 01_preprocessing_hsr.py                       # newest backup, all profiles
    python3 01_preprocessing_hsr.py --list-profile        # show available profiles
    python3 01_preprocessing_hsr.py --profile second      # single profile
    python3 01_preprocessing_hsr.py --input data/starrailstation-backup_2026-11-11.dat
    python3 01_preprocessing_hsr.py --tz Asia/Shanghai    # timezone for 'datetime'
"""

import argparse
import json
import re
from pathlib import Path

import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"

BACKUP_GLOB = "starrailstation-backup_*.dat"
CHAR_LOOKUP_PATH = DATA_DIR / "hsr_char_full.json"
LC_LOOKUP_PATH = DATA_DIR / "hsr_lc_full.json"

BACKUP_MAGIC = "srs"
DEFAULT_TZ = "Asia/Jakarta"

# gachaType -> display label (kept aligned with the Genshin labels where possible)
BANNER_LABELS = {
    1: "Standard",
    2: "Beginners",
    11: "Character Event",
    12: "Light Cone Event",
    21: "Collab Character Event",
    22: "Collab Light Cone Event",
}

# The 'result' field only has values on event banners for 4* and 5* pulls:
#   2 = won the 50/50 (got the rate-up item directly)
#   3 = guaranteed (got the rate-up item because the previous 4*/5* lost)
#   4 = lost the 50/50 (got the non rate-up item)
# 0 / missing = not applicable (3* pulls, Standard, Beginners)
RATE_LABELS = {2: "Win", 3: "Guaranteed", 4: "Lose"}


# --------------------------------------------------------------------------
# Backup decoding (LZString compressToUTF16 decoder, self-contained)
# --------------------------------------------------------------------------
def _lz_decompress(length: int, reset_value: int, get_next):
    dictionary = {0: 0, 1: 1, 2: 2}
    enlarge_in = 4
    dict_size = 4
    num_bits = 3
    result = []

    state = {"val": get_next(0), "pos": reset_value, "idx": 1}

    def read_bits(n: int) -> int:
        bits, power, maxpower = 0, 1, 2 ** n
        while power != maxpower:
            resb = state["val"] & state["pos"]
            state["pos"] >>= 1
            if state["pos"] == 0:
                state["pos"] = reset_value
                state["val"] = get_next(state["idx"]) if state["idx"] < length else 0
                state["idx"] += 1
            bits |= (1 if resb > 0 else 0) * power
            power <<= 1
        return bits

    first = read_bits(2)
    if first == 0:
        c = chr(read_bits(8))
    elif first == 1:
        c = chr(read_bits(16))
    else:
        return ""
    dictionary[3] = c
    w = c
    result.append(c)

    while True:
        if state["idx"] > length + 1:
            return ""
        cc = read_bits(num_bits)
        if cc == 0:
            dictionary[dict_size] = chr(read_bits(8))
            dict_size += 1
            cc = dict_size - 1
            enlarge_in -= 1
        elif cc == 1:
            dictionary[dict_size] = chr(read_bits(16))
            dict_size += 1
            cc = dict_size - 1
            enlarge_in -= 1
        elif cc == 2:
            return "".join(result)

        if enlarge_in == 0:
            enlarge_in = 2 ** num_bits
            num_bits += 1

        if cc in dictionary:
            entry = dictionary[cc]
        elif cc == dict_size:
            entry = w + w[0]
        else:
            raise ValueError("Corrupt backup: invalid LZString stream.")

        result.append(entry)
        dictionary[dict_size] = w + entry[0]
        dict_size += 1
        enlarge_in -= 1
        w = entry

        if enlarge_in == 0:
            enlarge_in = 2 ** num_bits
            num_bits += 1


def decode_backup(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith(BACKUP_MAGIC):
        raise ValueError(f"{path.name}: unexpected header, expected '{BACKUP_MAGIC}' prefix.")
    body = text[len(BACKUP_MAGIC):]
    decoded = _lz_decompress(len(body), 16384, lambda i: ord(body[i]) - 32)
    if not decoded:
        raise ValueError(f"{path.name}: could not decompress the backup.")
    return json.loads(decoded)


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------
def load_json(path: Path) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def find_latest_backup() -> Path:
    """Newest backup by the date in its filename (fallback: file mtime)."""
    candidates = list(DATA_DIR.glob(BACKUP_GLOB)) + list(BASE_DIR.glob(BACKUP_GLOB))
    if not candidates:
        raise FileNotFoundError(
            f"No '{BACKUP_GLOB}' file found in {DATA_DIR}. Put the backup there or use --input."
        )

    def sort_key(p: Path):
        m = re.search(r"(\d{4}-\d{2}-\d{2})", p.name)
        return (m.group(1) if m else "", p.stat().st_mtime)

    return max(candidates, key=sort_key)


def build_profile_map(raw: dict) -> dict:
    """
    profiles: {"1": {"name": "Default", ...}, "4": {"name": "second", ...}}
    Each profile's data lives in raw["data"]["stores"]["<key>_warp-v2"].
    Returns {key: {"name": ..., "store": {...}}} for profiles that have a warp store.
    """
    stores = raw.get("data", {}).get("stores", {})
    profiles = {}
    for key, info in raw.get("profiles", {}).items():
        store = stores.get(f"{key}_warp-v2")
        if store:
            profiles[str(key)] = {"name": info.get("name", str(key)), "store": store}
    return profiles


def slugify(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]+", "_", text).strip("_") or "profile"


def item_info(item_id, char_lookup: dict, lc_lookup: dict):
    """Returns (category, name, lookup_rarity). Category falls back to id length."""
    key = str(item_id)
    if key in char_lookup:
        e = char_lookup[key]
        return "character", e.get("name"), e.get("rarity")
    if key in lc_lookup:
        e = lc_lookup[key]
        return "light_cone", e.get("name"), e.get("rarity")
    # not in lookup: characters are 4-digit ids (1xxx/8xxx), light cones 5-digit (2xxxx)
    category = "light_cone" if len(key) == 5 else "character"
    return category, None, None


def pity_for_rarity(item: dict):
    """Pity counter that belongs to the pull's own rarity (5* -> pity5, 4* -> pity4)."""
    if item.get("rarity") == 5:
        return item.get("pity5")
    if item.get("rarity") == 4:
        return item.get("pity4")
    return None


def build_rows(profiles: dict, char_lookup: dict, lc_lookup: dict):
    rows = []
    n_rarity_mismatch = 0

    for key, prof in profiles.items():
        store = prof["store"]
        for gacha_type, banner_label in BANNER_LABELS.items():
            items = store.get(f"items_{gacha_type}", [])
            if not items:
                continue

            # sanity check: pullNo should be 1..N (a gap means a partial/incomplete history)
            pull_numbers = sorted(i.get("pullNo", 0) for i in items)
            if pull_numbers != list(range(1, len(items) + 1)):
                print(
                    f"[WARN] profile '{prof['name']}' / {banner_label}: pullNo is not a "
                    f"contiguous 1..{len(items)} sequence (history may be incomplete)."
                )

            for it in items:
                category, name, lookup_rarity = item_info(it.get("itemId"), char_lookup, lc_lookup)
                if lookup_rarity is not None and lookup_rarity != it.get("rarity"):
                    n_rarity_mismatch += 1

                result = it.get("result")
                rows.append(
                    {
                        "game": "hsr",
                        "account": prof["name"],
                        "profile_key": key,
                        "banner_type": banner_label,
                        "banner_code": it.get("gachaId"),
                        "pull_number": it.get("pullNo"),
                        "timestamp_ms": it.get("timestamp"),
                        "item_id": it.get("itemId"),
                        "item_name": name if name else it.get("itemId"),
                        "item_category": category,
                        "rarity": it.get("rarity"),
                        "pity": pity_for_rarity(it),
                        "pity4": it.get("pity4"),
                        "pity5": it.get("pity5"),
                        "rate_raw": result,
                        "win_50_50": RATE_LABELS.get(result),
                        "manual_input": it.get("manual"),
                        "pull_uid": it.get("uid"),
                    }
                )

    if n_rarity_mismatch:
        print(f"[WARN] {n_rarity_mismatch} row(s): rarity in backup differs from the lookup file.")
    return pd.DataFrame(rows)


def postprocess(df: pd.DataFrame, tz: str) -> pd.DataFrame:
    ts = pd.to_datetime(df["timestamp_ms"], unit="ms", utc=True, errors="coerce")
    df["datetime"] = ts.dt.tz_convert(tz).dt.tz_localize(None)
    df = df.drop(columns=["timestamp_ms"])

    n_bad = df["datetime"].isna().sum()
    if n_bad:
        print(f"[WARN] {n_bad} row(s) have an unparseable timestamp and were dropped.")
        df = df[df["datetime"].notna()].copy()

    n_dup = df.duplicated(subset=["profile_key", "pull_uid"]).sum()
    if n_dup:
        print(f"[WARN] {n_dup} duplicated pull_uid row(s) dropped.")
        df = df.drop_duplicates(subset=["profile_key", "pull_uid"])

    df = df.sort_values(["account", "banner_type", "datetime", "pull_number"]).reset_index(drop=True)

    df["date"] = df["datetime"].dt.date
    df["year_month"] = df["datetime"].dt.to_period("M").astype(str)
    df["is_5star"] = df["rarity"] == 5
    df["is_4star"] = df["rarity"] == 4
    df["is_3star"] = df["rarity"] == 3

    n_unmapped = (df["item_name"].astype(str) == df["item_id"].astype(str)).sum()
    if n_unmapped:
        ids = sorted(df.loc[df["item_name"].astype(str) == df["item_id"].astype(str), "item_id"].unique())
        print(
            f"[WARN] {n_unmapped} row(s) have no name mapping (item_id: {ids}). "
            "Re-run 00_fetch_hsr_lookup.py."
        )

    cols = [
        "game", "account", "profile_key", "banner_type", "banner_code", "pull_number",
        "datetime", "item_id", "item_name", "item_category", "rarity", "pity", "pity4",
        "pity5", "rate_raw", "win_50_50", "manual_input", "pull_uid",
        "date", "year_month", "is_5star", "is_4star", "is_3star",
    ]
    return df[cols]


def parse_args():
    parser = argparse.ArgumentParser(
        description="Preprocess the StarRailStation backup into a tidy CSV for EDA."
    )
    parser.add_argument("--input", type=str, default=None,
                        help="Path to a specific .dat backup. Default: newest backup in data/.")
    parser.add_argument("--profile", type=str, default=None,
                        help="Only process this profile (name or key). Default: all profiles.")
    parser.add_argument("--list-profile", action="store_true",
                        help="Show the profiles in the backup, then exit.")
    parser.add_argument("--tz", type=str, default=DEFAULT_TZ,
                        help=f"Timezone for the 'datetime' column (default: {DEFAULT_TZ}).")
    return parser.parse_args()


def main():
    args = parse_args()

    backup_path = Path(args.input) if args.input else find_latest_backup()
    print(f"Backup file: {backup_path}")
    raw = decode_backup(backup_path)
    profiles = build_profile_map(raw)

    print("Detected profiles:")
    for key, prof in profiles.items():
        n = sum(len(prof["store"].get(f"items_{t}", [])) for t in BANNER_LABELS)
        print(f"  - key={key}: name={prof['name']}, pulls={n}")
    if args.list_profile:
        return

    if not CHAR_LOOKUP_PATH.exists() or not LC_LOOKUP_PATH.exists():
        raise FileNotFoundError(
            "Lookup files not found. Run first: python3 00_fetch_hsr_lookup.py"
        )

    if args.profile:
        target = args.profile.strip().lower()
        selected = {
            k: p for k, p in profiles.items()
            if k.lower() == target or p["name"].lower() == target
        }
        if not selected:
            available = ", ".join(f"{k} ({p['name']})" for k, p in profiles.items())
            raise ValueError(f"Profile '{args.profile}' not found. Available: {available}")
        profiles = selected
        out_path = DATA_DIR / f"data_clean_hsr_{slugify(next(iter(profiles.values()))['name'])}.csv"
    else:
        out_path = DATA_DIR / "data_clean_hsr.csv"

    char_lookup = load_json(CHAR_LOOKUP_PATH)
    lc_lookup = load_json(LC_LOOKUP_PATH)

    df = build_rows(profiles, char_lookup, lc_lookup)
    df = postprocess(df, args.tz)

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False)

    print(f"\nTotal rows (warps): {len(df):,}")
    print(f"Time range          : {df['datetime'].min()} -> {df['datetime'].max()} ({args.tz})")
    print("\nWarps per banner:")
    print(df["banner_type"].value_counts().to_string())
    print("\nRarity distribution:")
    print(df["rarity"].value_counts(dropna=False).sort_index().to_string())
    print("\nWin/Lose 50-50 per rarity (event banners, 4* & 5*):")
    print(
        df[df["win_50_50"].notna()]
        .groupby(["rarity", "win_50_50"])
        .size()
        .to_string()
    )
    print(f"\nOutput file saved to: {out_path}")


if __name__ == "__main__":
    main()

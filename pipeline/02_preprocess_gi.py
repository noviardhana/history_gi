"""
02_preprocess_gi.py
====================
Preprocessing pipeline: paimon-moe-local-data.json -> data_clean_gi.csv

Converts the raw Paimon.moe export (Genshin Impact wish/gacha history) into
one tidy table (one row = one pull) ready for EDA & the dashboard
(Total Pull, Timeline, Pity Distribution, Win/Lose 50-50, Top
Character/Weapon, Banner Performance, Luck Score, etc.).

Input:
    data/paimon-moe-local-data.json   -> raw export
    data/char_full.json               -> id -> {name, rarity} lookup for characters
    data/weapon_full.json             -> id -> {name, rarity} lookup for weapons
    (both lookup files above are generated by 01_fetch_gi_lookup.py --
    run that script first before this one)

Output:
    data/data_clean_gi.csv            -> default, all UIDs combined
    data/data_clean_gi_<uid>.csv      -> when run with --uid <uid>

Usage:
    python3 pipeline/02_preprocess_gi.py                 # all accounts -> data_clean_gi.csv
    python3 pipeline/02_preprocess_gi.py --list-uid      # show available UIDs
    python3 pipeline/02_preprocess_gi.py --uid 887284572 # single account -> data_clean_gi_887284572.csv
    python3 pipeline/02_preprocess_gi.py --source-tz Asia/Jakarta --tz Asia/Jakarta
    python3 pipeline/02_preprocess_gi.py --keep-duplicates   # skip duplicate removal
    python3 pipeline/02_preprocess_gi.py --mask-uid          # 887284572 -> 88xxxxx72 in the output

Timezone: the Paimon.moe export has no timezone, so the timestamps are taken as
--source-tz (default: DEFAULT_TZ in config.py) and converted to --tz (default: the same
DEFAULT_TZ that the Star Rail script uses). With both defaults nothing is shifted.

Duplicates: a 10-pull that appears more than once (typical for merged exports) is cut back
to one copy. Single rows are never compared, because 3* rows always carry pity=1 and a real
10-pull often contains the same item several times. Suspicious cases are only reported.

Privacy: --mask-uid (or env GACHA_MASK_UID=1) replaces the UID in the output by a masked
form (887284572 -> 88xxxxx72), which is also what Google Sheet tab names and the dashboard show.
"""

import argparse
import json
import os
from pathlib import Path

import pandas as pd

from config import DATA_DIR, DEFAULT_TZ, GI_CLEAN
from logsetup import get_logger

log = get_logger("preprocess_gi")

RAW_PATH = DATA_DIR / "paimon-moe-local-data.json"
CHAR_LOOKUP_PATH = DATA_DIR / "char_full.json"
WEAPON_LOOKUP_PATH = DATA_DIR / "weapon_full.json"

# Banner key -> cleaner display label
BANNER_LABELS = {
    "wish-counter-character-event": "Character Event",
    "wish-counter-standard": "Standard",
    "wish-counter-weapon-event": "Weapon Event",
    "wish-counter-beginners": "Beginners",
}

# The 'rate' field only exists on event banners (Character Event & Weapon Event)
# for 4-star and 5-star pulls, representing the rate-up/50-50 outcome:
#   0 = lost the 50/50 (got the standard/non rate-up item)
#   1 = won the 50/50 (got the rate-up item directly)
#   2 = guaranteed (got the rate-up item because the previous pull lost)
RATE_LABELS = {0: "Lose", 1: "Win", 2: "Guaranteed"}


def load_json(path: Path) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def build_account_map(raw: dict) -> dict:
    """
    The raw data stores multiple accounts:
      - main (active) account -> keys WITHOUT a prefix, e.g. 'wish-counter-standard'
      - other accounts        -> keys WITH a prefix, e.g. 'account2-wish-counter-standard'
    Returns a dict:
      { account_label: {"prefix": "" / "account2-" / ..., "uid": ..., "ar": ..., "wl": ...} }
    """
    other_accounts = [a.strip() for a in raw.get("accounts", "").split(",") if a.strip()]

    accounts = {
        "main": {
            "prefix": "",
            "uid": raw.get("wish-uid"),
            "ar": raw.get("ar"),
            "wl": raw.get("wl"),
        }
    }
    for acc in other_accounts:
        accounts[acc] = {
            "prefix": f"{acc}-",
            "uid": raw.get(f"{acc}-wish-uid"),
            "ar": raw.get(f"{acc}-ar"),
            "wl": raw.get(f"{acc}-wl"),
        }
    return accounts


def rarity_and_name(item_id, item_type: str, char_lookup: dict, weapon_lookup: dict):
    lookup = char_lookup if item_type == "character" else weapon_lookup
    # BUG FIX: JSON object keys are always strings. If the export ever yields
    # item_id as an int, a direct dict lookup silently misses even though the
    # entry exists, inflating the "unmapped rarity" warning. Coerce to str.
    entry = lookup.get(str(item_id))
    if entry is None:
        return None, None
    return entry.get("rarity"), entry.get("name")


def build_rows(raw: dict, accounts: dict, char_lookup: dict, weapon_lookup: dict):
    rows = []

    for account_label, acc_info in accounts.items():
        prefix = acc_info["prefix"]

        for banner_key, banner_label in BANNER_LABELS.items():
            full_key = f"{prefix}{banner_key}"
            banner_data = raw.get(full_key)
            if not banner_data:
                continue

            pulls = banner_data.get("pulls", [])
            for pull_number, p in enumerate(pulls, start=1):
                item_id = p.get("id")
                item_type = p.get("type")  # 'character' or 'weapon'
                rarity, item_name = rarity_and_name(item_id, item_type, char_lookup, weapon_lookup)

                rate_raw = p.get("rate")
                win_50_50 = RATE_LABELS.get(rate_raw) if rate_raw is not None else None

                rows.append(
                    {
                        "account": account_label,
                        "uid": acc_info["uid"],
                        "adventure_rank": acc_info["ar"],
                        "world_level": acc_info["wl"],
                        "banner_type": banner_label,
                        "banner_code": p.get("code"),
                        "pull_number": pull_number,
                        "datetime": p.get("time"),
                        "item_id": item_id,
                        "item_name": item_name if item_name else item_id,
                        "item_category": item_type,
                        "rarity": rarity,
                        "pity": p.get("pity"),
                        "rate_raw": rate_raw,
                        "win_50_50": win_50_50,
                        "manual_input": p.get("manualInput"),
                    }
                )

    return pd.DataFrame(rows)


MAX_PULLS_PER_SECOND = 10  # a 10-pull shares one timestamp; more rows than this in one second means copied rows


def to_target_tz(series: pd.Series, source_tz: str, tz: str) -> pd.Series:
    """Naive timestamps in `source_tz` -> naive timestamps in `tz` (timezone-aware input is just converted)."""
    dt = pd.to_datetime(series, errors="coerce")
    if dt.dt.tz is None:
        if source_tz == tz:
            return dt
        # ambiguous / non-existent local times (DST) become NaT and are reported below
        dt = dt.dt.tz_localize(source_tz, ambiguous="NaT", nonexistent="NaT")
    return dt.dt.tz_convert(tz).dt.tz_localize(None)


def drop_duplicate_pulls(df: pd.DataFrame) -> pd.DataFrame:
    """
    Remove rows that were copied by merging overlapping exports.

    Paimon.moe pulls have no unique id, and 3* rows always carry pity=1, so rows can NOT be
    compared one by one: a real 10-pull often holds the same 3* item several times in the
    same second. What a merge does produce is a whole 10-pull appearing twice, i.e. more than
    10 rows in one second (account + banner). Only such a group, and only when it is an exact
    repeat of a 10-row block, is cut back to one block. Anything else is reported, never dropped.
    """
    cols = ["item_id", "item_category", "rarity", "pity", "rate_raw"]
    drop, suspicious = [], 0
    for _, g in df.groupby(["account", "banner_type", "datetime"], sort=False):
        n = len(g)
        if n <= MAX_PULLS_PER_SECOND:
            continue
        # NaN != NaN, so make missing values comparable before comparing the rows
        block = list(g[cols].astype(object).fillna("<NA>").itertuples(index=False, name=None))
        k = MAX_PULLS_PER_SECOND
        if n % k == 0 and block == block[:k] * (n // k):
            drop.extend(g.index[k:])
        else:
            suspicious += 1
    if suspicious:
        log.warning(f"{suspicious} second(s) hold more than {MAX_PULLS_PER_SECOND} pulls but are not an exact "
              "repeat of a 10-pull; nothing was dropped there. Check the export.")
    if not drop:
        return df
    log.warning(f"{len(drop)} duplicated pull(s) dropped (a 10-pull that appeared more than once).")
    df = df.drop(index=drop).copy()
    # keep pull_number a clean 1..N sequence per banner (rows are still in original order here)
    df["pull_number"] = df.groupby(["account", "banner_type"]).cumcount() + 1
    return df


def postprocess(df: pd.DataFrame, source_tz: str = DEFAULT_TZ, tz: str = DEFAULT_TZ,
                keep_duplicates: bool = False) -> pd.DataFrame:
    df["datetime"] = to_target_tz(df["datetime"], source_tz, tz)

    # BUG FIX: rows whose datetime couldn't be parsed become NaT, which then
    # leaked into year_month as the literal string "NaT" with no warning.
    n_bad_datetime = df["datetime"].isna().sum()
    if n_bad_datetime:
        log.warning(f"{n_bad_datetime} row(s) have an unparseable datetime and were dropped.")
        df = df[df["datetime"].notna()].copy()

    if not keep_duplicates:
        df = drop_duplicate_pulls(df)

    df = df.sort_values(["account", "banner_type", "datetime", "pull_number"]).reset_index(drop=True)

    # derived columns (convenience for EDA)
    df["date"] = df["datetime"].dt.date
    df["year_month"] = df["datetime"].dt.to_period("M").astype(str)
    df["is_5star"] = df["rarity"] == 5
    df["is_4star"] = df["rarity"] == 4
    df["is_3star"] = df["rarity"] == 3

    # rarity with no matching lookup entry -> flag it (data quality check)
    n_unmapped = df["rarity"].isna().sum()
    if n_unmapped:
        log.warning(f"{n_unmapped} row(s) have no rarity mapping (unrecognized item_id).")

    return df


def mask_uid(uid, keep: int = 2) -> str:
    """887284572 -> 88xxxxx72 (first and last `keep` digits stay)."""
    u = str(uid)
    if len(u) <= keep * 2:
        return "x" * len(u)
    return u[:keep] + "x" * (len(u) - keep * 2) + u[-keep:]


def mask_uids(df: pd.DataFrame) -> pd.DataFrame:
    """Mask the uid column. Uses more digits if two different UIDs would end up with the same mask."""
    real = df["uid"].dropna().astype(str).unique()
    keep = 2
    while keep < 4 and len({mask_uid(u, keep) for u in real}) < len(real):
        keep += 1
    df = df.copy()
    df["uid"] = df["uid"].map(lambda u: mask_uid(u, keep) if pd.notna(u) else u)
    return df


def env_flag(name: str) -> bool:
    return os.environ.get(name, "").strip().lower() in ("1", "true", "yes")


def parse_args():
    parser = argparse.ArgumentParser(
        description="Preprocess the paimon-moe wish export into a tidy CSV for EDA."
    )
    parser.add_argument(
        "--uid",
        type=str,
        default=None,
        help="Only process the account with this UID. Leave empty to process all accounts.",
    )
    parser.add_argument(
        "--source-tz", type=str, default=DEFAULT_TZ,
        help=f"Timezone the export's timestamps are in (default: {DEFAULT_TZ}).",
    )
    parser.add_argument(
        "--tz", type=str, default=DEFAULT_TZ,
        help=f"Timezone for the 'datetime' column (default: {DEFAULT_TZ}, same as the Star Rail script).",
    )
    parser.add_argument(
        "--mask-uid", action="store_true", default=env_flag("GACHA_MASK_UID"),
        help="Mask the UID in the output (887284572 -> 88xxxxx72). Also enabled by env GACHA_MASK_UID=1.",
    )
    parser.add_argument(
        "--keep-duplicates", action="store_true",
        help="Do not remove duplicate pulls.",
    )
    parser.add_argument(
        "--list-uid",
        action="store_true",
        help="Show the UIDs available in the export file, then exit.",
    )
    return parser.parse_args()


def main():
    args = parse_args()

    raw = load_json(RAW_PATH)
    accounts = build_account_map(raw)

    if args.list_uid:
        # BUG FIX: listing UIDs doesn't need the rarity lookup files, so the
        # lookup-file check below must not block this path. Handle it first.
        print("UIDs available in the export file:")
        for label, info in accounts.items():
            print(f"  - {label}: uid={info['uid']}, AR={info['ar']}, WL={info['wl']}")
        return

    if not CHAR_LOOKUP_PATH.exists() or not WEAPON_LOOKUP_PATH.exists():
        raise FileNotFoundError(
            "Rarity lookup files not found. Run first: python3 pipeline/01_fetch_gi_lookup.py"
        )

    print("Detected accounts:")
    for label, info in accounts.items():
        print(f"  - {label}: uid={info['uid']}, AR={info['ar']}, WL={info['wl']}")

    # If the user requested a specific uid, filter the account list before
    # build_rows for efficiency, and so the output file only contains that account.
    if args.uid:
        target_uid = str(args.uid)
        accounts = {
            label: info for label, info in accounts.items()
            if str(info["uid"]) == target_uid
        }
        if not accounts:
            available = ", ".join(str(info["uid"]) for info in build_account_map(raw).values())
            raise ValueError(
                f"UID '{args.uid}' not found. Available UIDs: {available}"
            )
        file_uid = mask_uid(target_uid) if args.mask_uid else target_uid
        out_path = GI_CLEAN.with_name(f"data_clean_gi_{file_uid}.csv")
    else:
        out_path = GI_CLEAN

    char_lookup = load_json(CHAR_LOOKUP_PATH)
    weapon_lookup = load_json(WEAPON_LOOKUP_PATH)

    df = build_rows(raw, accounts, char_lookup, weapon_lookup)
    df = postprocess(df, args.source_tz, args.tz, args.keep_duplicates)
    if args.mask_uid:
        df = mask_uids(df)
        log.info("UID masked in the output file.")

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False)

    print(f"\nTotal rows (pulls): {len(df):,}")
    print(f"Time range          : {df['datetime'].min()} -> {df['datetime'].max()} ({args.tz})")
    print("\nPulls per banner:")
    print(df["banner_type"].value_counts().to_string())
    print("\nRarity distribution:")
    print(df["rarity"].value_counts(dropna=False).sort_index().to_string())
    print("\nWin/Lose 50-50 per rarity (event banners, 4* & 5*):")
    print(
        df[df["win_50_50"].notna()]
        .groupby(["rarity", "win_50_50"])
        .size()
        .to_string()
    )
    print(f"\nOutput file saved to: {out_path}")


if __name__ == "__main__":
    main()
"""
preprocess.py
=============
Raw export -> one tidy CSV (one row = one pull) for EDA, the dashboard and the Google Sheet.
(Merged from the former 02_preprocess_gi.py and 02_preprocess_hsr.py; the game-specific
parsers stay separate, everything that was identical is shared.)

Genshin Impact (--game gi)
    Input : data/paimon-moe-local-data.json, data/char_full.json, data/weapon_full.json
    Output: data/data_clean_gi.csv            (all UIDs)
            data/data_clean_gi_<uid>.csv      (with --uid)
    * The Paimon.moe export has no timezone: timestamps are taken as --source-tz and
      converted to --tz (both default to DEFAULT_TZ, so nothing is shifted).
    * A 10-pull that appears more than once (merged exports) is cut back to one copy.
      Single rows are never compared (3* rows always carry pity=1). Suspicious cases are
      only reported.
    * --mask-uid (or env GACHA_MASK_UID=1) masks the UID: 887284572 -> 88xxxxx72.

Honkai: Star Rail (--game hsr)
    Input : data/starrailstation-backup_YYYY-MM-DD.dat (newest is picked automatically),
            data/hsr_char_full.json, data/hsr_lc_full.json
    Output: data/data_clean_hsr.csv           (all profiles)
            data/data_clean_hsr_<profile>.csv (with --profile)
    * The .dat file is "srs" + an LZString(UTF-16) compressed JSON, decoded below.
    * Every backup is a FULL snapshot, so each run rebuilds the CSV from the newest backup.
    * The backup has no game UID. Accounts are the StarRailStation profiles.

The lookup files are generated by fetch_lookup.py (run it first).

Usage:
    python -m pipeline preprocess [--games gi,hsr]
    python pipeline/preprocess.py --game gi --list-uid
    python pipeline/preprocess.py --game gi --uid 887284572 --mask-uid
    python pipeline/preprocess.py --game hsr --profile second
    python pipeline/preprocess.py --game hsr --input data/starrailstation-backup_2026-11-11.dat
"""


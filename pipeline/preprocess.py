def load_json(path: Path) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def add_derived_columns(df: pd.DataFrame) -> pd.DataFrame:
    """date / year_month / is_Nstar. The star flags are computed before rarity becomes nullable Int64."""
    df["date"] = df["datetime"].dt.date
    df["year_month"] = df["datetime"].dt.to_period("M").astype(str)
    for n in (5, 4, 3):
        df[f"is_{n}star"] = df["rarity"] == n
    # Int64 keeps 5 as "5" in the CSV even when some rarity is missing (a float column would write "5.0")
    df["rarity"] = pd.to_numeric(df["rarity"], errors="coerce").astype("Int64")
    return df


def print_summary(df: pd.DataFrame, out_path: Path, tz: str, noun: str):
    print(f"\nTotal rows ({noun}s): {len(df):,}")
    print(f"Time range          : {df['datetime'].min()} -> {df['datetime'].max()} ({tz})")
    print(f"\n{noun.capitalize()}s per banner:")
    print(df["banner_type"].value_counts().to_string())
    print("\nRarity distribution:")
    print(df["rarity"].value_counts(dropna=False).sort_index().to_string())
    print("\nWin/Lose 50-50 per rarity (event banners, 4* & 5*):")
    print(df[df["win_50_50"].notna()].groupby(["rarity", "win_50_50"]).size().to_string())
    print(f"\nOutput file saved to: {out_path}")


def require_rows(df: pd.DataFrame, source: str):
    if df.empty:
        raise ValueError(f"No pulls found in {source}. Is the export empty?")



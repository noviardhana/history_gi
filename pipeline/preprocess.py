GI_RAW_PATH = DATA_DIR / "paimon-moe-local-data.json"
GI_CHAR_LOOKUP = DATA_DIR / "char_full.json"
GI_WEAPON_LOOKUP = DATA_DIR / "weapon_full.json"

GI_BANNER_LABELS = {
    "wish-counter-character-event": "Character Event",
    "wish-counter-standard": "Standard",
    "wish-counter-weapon-event": "Weapon Event",
    "wish-counter-beginners": "Beginners",
}

# The 'rate' field only exists on event banners for 4* and 5* pulls:
#   0 = lost the 50/50, 1 = won the 50/50, 2 = guaranteed (previous 4*/5* lost)
GI_RATE_LABELS = {0: "Lose", 1: "Win", 2: "Guaranteed"}

MAX_PULLS_PER_SECOND = 10  # a 10-pull shares one timestamp; more rows than this in one second means copied rows


def build_account_map(raw: dict) -> dict:
    """
    main (active) account -> keys WITHOUT a prefix, e.g. 'wish-counter-standard'
    other accounts        -> keys WITH a prefix,    e.g. 'account2-wish-counter-standard'
    Returns { account_label: {"prefix": "" / "account2-", "uid": ..., "ar": ..., "wl": ...} }
    """
    other_accounts = [a.strip() for a in raw.get("accounts", "").split(",") if a.strip()]
    accounts = {"main": {"prefix": "", "uid": raw.get("wish-uid"), "ar": raw.get("ar"), "wl": raw.get("wl")}}
    for acc in other_accounts:
        accounts[acc] = {
            "prefix": f"{acc}-",
            "uid": raw.get(f"{acc}-wish-uid"),
            "ar": raw.get(f"{acc}-ar"),
            "wl": raw.get(f"{acc}-wl"),
        }
    return accounts


def rarity_and_name(item_id, item_type: str, char_lookup: dict, weapon_lookup: dict):
    lookup = char_lookup if item_type == "character" else weapon_lookup
    entry = lookup.get(str(item_id))  # JSON keys are always strings
    if entry is None:
        return None, None
    return entry.get("rarity"), entry.get("name")


def warn_unknown_banners(raw: dict, accounts: dict):
    """A banner key in the export that GI_BANNER_LABELS does not know would be silently ignored."""
    known = {f"{info['prefix']}{k}" for info in accounts.values() for k in GI_BANNER_LABELS}
    for info in accounts.values():
        marker = f"{info['prefix']}wish-counter-"
        for key, value in raw.items():
            if key.startswith(marker) and key not in known and isinstance(value, dict) and value.get("pulls"):
                log.warning(f"banner '{key}' has {len(value['pulls'])} pull(s) but is not in GI_BANNER_LABELS; it was ignored.")


def build_rows_gi(raw: dict, accounts: dict, char_lookup: dict, weapon_lookup: dict) -> pd.DataFrame:
    warn_unknown_banners(raw, accounts)
    rows = []
    for account_label, acc_info in accounts.items():
        prefix = acc_info["prefix"]
        for banner_key, banner_label in GI_BANNER_LABELS.items():
            banner_data = raw.get(f"{prefix}{banner_key}")
            if not banner_data:
                continue
            for pull_number, p in enumerate(banner_data.get("pulls", []), start=1):
                item_id = p.get("id")
                item_type = p.get("type")  # 'character' or 'weapon'
                rarity, item_name = rarity_and_name(item_id, item_type, char_lookup, weapon_lookup)
                rate_raw = p.get("rate")
                rows.append(
                    {
                        "account": account_label,
                        "uid": acc_info["uid"],
                        "adventure_rank": acc_info["ar"],
                        "world_level": acc_info["wl"],
                        "banner_type": banner_label,
                        "banner_code": p.get("code"),
                        "pull_number": pull_number,
                        "datetime": p.get("time"),
                        "item_id": item_id,
                        "item_name": item_name if item_name else item_id,
                        "item_category": item_type,
                        "rarity": rarity,
                        "pity": p.get("pity"),
                        "rate_raw": rate_raw,
                        "win_50_50": GI_RATE_LABELS.get(rate_raw) if rate_raw is not None else None,
                        "manual_input": p.get("manualInput"),
                    }
                )
    return pd.DataFrame(rows)


def to_target_tz(series: pd.Series, source_tz: str, tz: str) -> pd.Series:
    """Naive timestamps in `source_tz` -> naive timestamps in `tz` (timezone-aware input is just converted)."""
    dt = pd.to_datetime(series, errors="coerce")
    if dt.dt.tz is None:
        if source_tz == tz:
            return dt
        # ambiguous / non-existent local times (DST) become NaT and are reported by the caller
        dt = dt.dt.tz_localize(source_tz, ambiguous="NaT", nonexistent="NaT")
    return dt.dt.tz_convert(tz).dt.tz_localize(None)


def drop_duplicate_pulls(df: pd.DataFrame) -> pd.DataFrame:
    """
    Remove rows copied by merging overlapping exports. A merge produces a whole 10-pull twice,
    i.e. more than 10 rows in one second (account + banner). Only such a group, and only when it
    is an exact repeat of a 10-row block, is cut back to one block. Anything else is reported.
    """
    cols = ["item_id", "item_category", "rarity", "pity", "rate_raw"]
    drop, suspicious = [], 0
    for _, g in df.groupby(["account", "banner_type", "datetime"], sort=False):
        n = len(g)
        if n <= MAX_PULLS_PER_SECOND:
            continue
        # NaN != NaN, so make missing values comparable before comparing the rows
        block = list(g[cols].astype(object).fillna("<NA>").itertuples(index=False, name=None))
        k = MAX_PULLS_PER_SECOND
        if n % k == 0 and block == block[:k] * (n // k):
            drop.extend(g.index[k:])
        else:
            suspicious += 1
    if suspicious:
        log.warning(f"{suspicious} second(s) hold more than {MAX_PULLS_PER_SECOND} pulls but are not an exact "
                    "repeat of a 10-pull; nothing was dropped there. Check the export.")
    if not drop:
        return df
    log.warning(f"{len(drop)} duplicated pull(s) dropped (a 10-pull that appeared more than once).")
    df = df.drop(index=drop).copy()
    df["pull_number"] = df.groupby(["account", "banner_type"]).cumcount() + 1  # keep 1..N per banner
    return df


def postprocess_gi(df: pd.DataFrame, source_tz: str, tz: str, keep_duplicates: bool = False) -> pd.DataFrame:
    df["datetime"] = to_target_tz(df["datetime"], source_tz, tz)

    n_bad = df["datetime"].isna().sum()
    if n_bad:
        log.warning(f"{n_bad} row(s) have an unparseable datetime and were dropped.")
        df = df[df["datetime"].notna()].copy()

    if not keep_duplicates:
        df = drop_duplicate_pulls(df)

    df = df.sort_values(["account", "banner_type", "datetime", "pull_number"]).reset_index(drop=True)

    n_unmapped = df["rarity"].isna().sum()
    if n_unmapped:
        log.warning(f"{n_unmapped} row(s) have no rarity mapping (unrecognized item_id). "
                    "Re-run: python -m pipeline fetch --games gi")
    return add_derived_columns(df)


def mask_uids(df: pd.DataFrame) -> pd.DataFrame:
    """Mask the uid column. Uses more digits if two different UIDs would end up with the same mask."""
    real = df["uid"].dropna().astype(str).unique()
    keep = 2
    while keep < 4 and len({mask_uid(u, keep) for u in real}) < len(real):
        keep += 1
    df = df.copy()
    df["uid"] = df["uid"].map(lambda u: mask_uid(u, keep) if pd.notna(u) else u)
    return df


def run_gi(args) -> int:
    raw = load_json(GI_RAW_PATH)
    accounts = build_account_map(raw)

    print("Detected accounts:")
    for label, info in accounts.items():
        print(f"  - {label}: uid={info['uid']}, AR={info['ar']}, WL={info['wl']}")
    if args.list_accounts:  # listing needs no lookup files
        return 0

    if not GI_CHAR_LOOKUP.exists() or not GI_WEAPON_LOOKUP.exists():
        raise FileNotFoundError("Rarity lookup files not found. Run first: python -m pipeline fetch --games gi")

    out_path = GI_CLEAN
    if args.account:
        target = str(args.account)
        selected = {k: v for k, v in accounts.items() if str(v["uid"]) == target}
        if not selected:
            available = ", ".join(str(v["uid"]) for v in accounts.values())
            raise ValueError(f"UID '{args.account}' not found. Available UIDs: {available}")
        accounts = selected
        file_uid = mask_uid(target) if args.mask_uid else target
        out_path = GI_CLEAN.with_name(f"data_clean_gi_{file_uid}.csv")

    df = build_rows_gi(raw, accounts, load_json(GI_CHAR_LOOKUP), load_json(GI_WEAPON_LOOKUP))
    require_rows(df, GI_RAW_PATH.name)
    df = postprocess_gi(df, args.source_tz, args.tz, args.keep_duplicates)
    require_rows(df, GI_RAW_PATH.name)
    if args.mask_uid:
        df = mask_uids(df)
        log.info("UID masked in the output file.")

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False)
    print_summary(df, out_path, args.tz, "pull")
    return 0



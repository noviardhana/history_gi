HSR_BACKUP_GLOB = "starrailstation-backup_*.dat"
HSR_CHAR_LOOKUP = DATA_DIR / "hsr_char_full.json"
HSR_LC_LOOKUP = DATA_DIR / "hsr_lc_full.json"
HSR_BACKUP_MAGIC = "srs"

HSR_BANNER_LABELS = {
    1: "Standard",
    2: "Beginners",
    11: "Character Event",
    12: "Light Cone Event",
    21: "Collab Character Event",
    22: "Collab Light Cone Event",
}

# 'result' only has values on event banners for 4* and 5* pulls:
#   2 = won the 50/50, 3 = guaranteed, 4 = lost the 50/50; 0 / missing = not applicable
HSR_RATE_LABELS = {2: "Win", 3: "Guaranteed", 4: "Lose"}


def _lz_decompress(length: int, reset_value: int, get_next):
    """LZString compressToUTF16 decoder (self-contained, no extra package)."""
    dictionary = {0: 0, 1: 1, 2: 2}
    enlarge_in = 4
    dict_size = 4
    num_bits = 3
    result = []

    state = {"val": get_next(0), "pos": reset_value, "idx": 1}

    def read_bits(n: int) -> int:
        bits, power, maxpower = 0, 1, 2 ** n
        while power != maxpower:
            resb = state["val"] & state["pos"]
            state["pos"] >>= 1
            if state["pos"] == 0:
                state["pos"] = reset_value
                state["val"] = get_next(state["idx"]) if state["idx"] < length else 0
                state["idx"] += 1
            bits |= (1 if resb > 0 else 0) * power
            power <<= 1
        return bits

    first = read_bits(2)
    if first == 0:
        c = chr(read_bits(8))
    elif first == 1:
        c = chr(read_bits(16))
    else:
        return ""
    dictionary[3] = c
    w = c
    result.append(c)

    while True:
        if state["idx"] > length + 1:
            return ""
        cc = read_bits(num_bits)
        if cc == 0:
            dictionary[dict_size] = chr(read_bits(8))
            dict_size += 1
            cc = dict_size - 1
            enlarge_in -= 1
        elif cc == 1:
            dictionary[dict_size] = chr(read_bits(16))
            dict_size += 1
            cc = dict_size - 1
            enlarge_in -= 1
        elif cc == 2:
            return "".join(result)

        if enlarge_in == 0:
            enlarge_in = 2 ** num_bits
            num_bits += 1

        if cc in dictionary:
            entry = dictionary[cc]
        elif cc == dict_size:
            entry = w + w[0]
        else:
            raise ValueError("Corrupt backup: invalid LZString stream.")

        result.append(entry)
        dictionary[dict_size] = w + entry[0]
        dict_size += 1
        enlarge_in -= 1
        w = entry

        if enlarge_in == 0:
            enlarge_in = 2 ** num_bits
            num_bits += 1


def decode_backup(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith(HSR_BACKUP_MAGIC):
        raise ValueError(f"{path.name}: unexpected header, expected '{HSR_BACKUP_MAGIC}' prefix.")
    body = text[len(HSR_BACKUP_MAGIC):]
    decoded = _lz_decompress(len(body), 16384, lambda i: ord(body[i]) - 32)
    if not decoded:
        raise ValueError(f"{path.name}: could not decompress the backup.")
    # LZString yields UTF-16 code units: characters outside the BMP (emoji) arrive as two
    # separate surrogates, which to_csv can not encode. Re-join the pairs into real characters.
    decoded = decoded.encode("utf-16-le", "surrogatepass").decode("utf-16-le", "replace")
    return json.loads(decoded)


def find_latest_backup() -> Path:
    """Newest backup by the date in its filename (fallback: file mtime)."""
    candidates = list(DATA_DIR.glob(HSR_BACKUP_GLOB)) + list(ROOT_DIR.glob(HSR_BACKUP_GLOB))
    if not candidates:
        raise FileNotFoundError(f"No '{HSR_BACKUP_GLOB}' file found in {DATA_DIR}. Put the backup there or use --input.")

    def sort_key(p: Path):
        m = re.search(r"(\d{4}-\d{2}-\d{2})", p.name)
        return (m.group(1) if m else "", p.stat().st_mtime)

    return max(candidates, key=sort_key)


def build_profile_map(raw: dict) -> dict:
    """Each profile's data lives in raw["data"]["stores"]["<key>_warp-v2"]. Returns {key: {"name", "store"}}."""
    stores = raw.get("data", {}).get("stores", {})
    profiles = {}
    for key, info in raw.get("profiles", {}).items():
        store = stores.get(f"{key}_warp-v2")
        if store:
            profiles[str(key)] = {"name": info.get("name", str(key)), "store": store}
    return profiles


def slugify(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]+", "_", text).strip("_") or "profile"


def item_info(item_id, char_lookup: dict, lc_lookup: dict):
    """Returns (category, name, lookup_rarity). Category falls back to id length."""
    key = str(item_id)
    if key in char_lookup:
        e = char_lookup[key]
        return "character", e.get("name"), e.get("rarity")
    if key in lc_lookup:
        e = lc_lookup[key]
        return "light_cone", e.get("name"), e.get("rarity")
    # characters are 4-digit ids (1xxx/8xxx), light cones 5-digit (2xxxx)
    return ("light_cone" if len(key) == 5 else "character"), None, None


def pity_for_rarity(item: dict):
    """Pity counter that belongs to the pull's own rarity (5* -> pity5, 4* -> pity4)."""
    if item.get("rarity") == 5:
        return item.get("pity5")
    if item.get("rarity") == 4:
        return item.get("pity4")
    return None


def build_rows_hsr(profiles: dict, char_lookup: dict, lc_lookup: dict) -> pd.DataFrame:
    rows = []
    n_rarity_mismatch = 0
    for key, prof in profiles.items():
        store = prof["store"]
        for gacha_type, banner_label in HSR_BANNER_LABELS.items():
            items = store.get(f"items_{gacha_type}", [])
            if not items:
                continue

            # pullNo should be 1..N (a gap means a partial/incomplete history)
            pull_numbers = sorted(i.get("pullNo", 0) for i in items)
            if pull_numbers != list(range(1, len(items) + 1)):
                log.warning(f"profile '{prof['name']}' / {banner_label}: pullNo is not a "
                            f"contiguous 1..{len(items)} sequence (history may be incomplete).")

            for it in items:
                category, name, lookup_rarity = item_info(it.get("itemId"), char_lookup, lc_lookup)
                if lookup_rarity is not None and lookup_rarity != it.get("rarity"):
                    n_rarity_mismatch += 1
                result = it.get("result")
                rows.append(
                    {
                        "game": "hsr",
                        "account": prof["name"],
                        "profile_key": key,
                        "banner_type": banner_label,
                        "banner_code": it.get("gachaId"),
                        "pull_number": it.get("pullNo"),
                        "timestamp_ms": it.get("timestamp"),
                        "item_id": it.get("itemId"),
                        "item_name": name if name else it.get("itemId"),
                        "item_category": category,
                        "rarity": it.get("rarity"),
                        "pity": pity_for_rarity(it),
                        "pity4": it.get("pity4"),
                        "pity5": it.get("pity5"),
                        "rate_raw": result,
                        "win_50_50": HSR_RATE_LABELS.get(result),
                        "manual_input": it.get("manual"),
                        "pull_uid": it.get("uid"),
                    }
                )
    if n_rarity_mismatch:
        log.warning(f"{n_rarity_mismatch} row(s): rarity in backup differs from the lookup file.")
    return pd.DataFrame(rows)


HSR_COLUMNS = [
    "game", "account", "profile_key", "banner_type", "banner_code", "pull_number",
    "datetime", "item_id", "item_name", "item_category", "rarity", "pity", "pity4",
    "pity5", "rate_raw", "win_50_50", "manual_input", "pull_uid",
    "date", "year_month", "is_5star", "is_4star", "is_3star",
]


def postprocess_hsr(df: pd.DataFrame, tz: str) -> pd.DataFrame:
    ts = pd.to_datetime(df["timestamp_ms"], unit="ms", utc=True, errors="coerce")
    df["datetime"] = ts.dt.tz_convert(tz).dt.tz_localize(None)
    df = df.drop(columns=["timestamp_ms"])

    n_bad = df["datetime"].isna().sum()
    if n_bad:
        log.warning(f"{n_bad} row(s) have an unparseable timestamp and were dropped.")
        df = df[df["datetime"].notna()].copy()

    # pandas treats missing values as equal, so rows without a pull_uid must be left out of the
    # comparison (otherwise they would all collapse into one row)
    n_no_uid = int(df["pull_uid"].isna().sum())
    if n_no_uid:
        log.warning(f"{n_no_uid} row(s) have no pull_uid; duplicates can not be checked for them.")
    dup = df.duplicated(subset=["profile_key", "pull_uid"]) & df["pull_uid"].notna()
    n_dup = int(dup.sum())
    if n_dup:
        log.warning(f"{n_dup} duplicated pull_uid row(s) dropped.")
        df = df[~dup]

    df = df.sort_values(["account", "banner_type", "datetime", "pull_number"]).reset_index(drop=True)

    unmapped = df["item_name"].astype(str) == df["item_id"].astype(str)
    if unmapped.any():
        ids = sorted(df.loc[unmapped, "item_id"].unique())
        log.warning(f"{int(unmapped.sum())} row(s) have no name mapping (item_id: {ids}). "
                    "Re-run: python -m pipeline fetch --games hsr")
    return add_derived_columns(df)[HSR_COLUMNS]


def run_hsr(args) -> int:
    backup_path = Path(args.input) if args.input else find_latest_backup()
    print(f"Backup file: {backup_path}")
    profiles = build_profile_map(decode_backup(backup_path))

    print("Detected profiles:")
    for key, prof in profiles.items():
        n = sum(len(prof["store"].get(f"items_{t}", [])) for t in HSR_BANNER_LABELS)
        print(f"  - key={key}: name={prof['name']}, pulls={n}")
    if args.list_accounts:
        return 0

    if not HSR_CHAR_LOOKUP.exists() or not HSR_LC_LOOKUP.exists():
        raise FileNotFoundError("Lookup files not found. Run first: python -m pipeline fetch --games hsr")

    out_path = HSR_CLEAN
    if args.account:
        target = args.account.strip().lower()
        selected = {k: p for k, p in profiles.items() if k.lower() == target or p["name"].lower() == target}
        if not selected:
            available = ", ".join(f"{k} ({p['name']})" for k, p in profiles.items())
            raise ValueError(f"Profile '{args.account}' not found. Available: {available}")
        profiles = selected
        out_path = HSR_CLEAN.with_name(f"data_clean_hsr_{slugify(next(iter(profiles.values()))['name'])}.csv")

    df = build_rows_hsr(profiles, load_json(HSR_CHAR_LOOKUP), load_json(HSR_LC_LOOKUP))
    require_rows(df, backup_path.name)
    df = postprocess_hsr(df, args.tz)
    require_rows(df, backup_path.name)

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False, encoding="utf-8")
    print_summary(df, out_path, args.tz, "warp")
    return 0


# ===========================================================================
def parse_args(argv=None):
    ap = argparse.ArgumentParser(description="Preprocess a Genshin (Paimon.moe) or Star Rail (StarRailStation) export into a tidy CSV.")
    ap.add_argument("--game", required=True, choices=["gi", "hsr"], help="gi or hsr")
    ap.add_argument("--uid", "--profile", dest="account", default=None,
                    help="Only this account: UID (gi) or profile name/key (hsr). Default: all.")
    ap.add_argument("--list-uid", "--list-profile", "--list", dest="list_accounts", action="store_true",
                    help="Show the accounts / profiles in the export, then exit.")
    ap.add_argument("--tz", default=DEFAULT_TZ, help=f"Timezone of the 'datetime' column (default: {DEFAULT_TZ}).")
    # Genshin only
    ap.add_argument("--source-tz", default=DEFAULT_TZ, help=f"[gi] timezone the export's timestamps are in (default: {DEFAULT_TZ}).")
    ap.add_argument("--mask-uid", action="store_true", default=env_flag("GACHA_MASK_UID"),
                    help="[gi] mask the UID (887284572 -> 88xxxxx72). Also enabled by env GACHA_MASK_UID=1.")
    ap.add_argument("--keep-duplicates", action="store_true", help="[gi] do not remove duplicate pulls.")
    # Star Rail only
    ap.add_argument("--input", default=None, help="[hsr] a specific .dat backup. Default: newest in data/.")
    args = ap.parse_args(argv)
    if args.game == "hsr" and args.keep_duplicates:
        ap.error("--keep-duplicates only applies to --game gi")
    if args.game == "gi" and args.input:
        ap.error("--input only applies to --game hsr")
    return args


def main(argv=None) -> int:
    args = parse_args(argv)
    return run_gi(args) if args.game == "gi" else run_hsr(args)


if __name__ == "__main__":
    sys.exit(main())
